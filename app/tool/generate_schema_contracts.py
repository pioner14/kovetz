"""Regenerate Dart fingerprints from reviewed schema-only contract profiles.

Run from the repository root. Python is a development tool, not an app runtime.
Profiles describe supported fixtures and observed 2019-2026 exports, plus the
app's canonical output; no user records, archive names or paths are included.
"""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parents[1]
profiles = json.loads((root / 'tool/schema_contracts.json').read_text())
lines = ['// Generated by app/tool/generate_schema_contracts.py; do not hand-edit.',
         '// Review tool/schema_contracts.json and add compatibility tests before changing.',
         'const knownSchemaContracts = <int, Map<String, Set<String>>>{']
for version, tables in sorted(profiles.items(), key=lambda x: int(x[0])):
    lines.append(f'  {version}: {{')
    for table, shapes in sorted(tables.items()):
        lines.append(f"    '{table}': {{")
        for digest in sorted({hashlib.sha256(json.dumps(shape, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest() for shape in shapes}):
            lines.append(f"      '{digest}',")
        lines.append('    },')
    lines.append('  },')
lines.append('};')
(root / 'lib/schema_contracts.dart').write_text('\n'.join(lines) + '\n')
